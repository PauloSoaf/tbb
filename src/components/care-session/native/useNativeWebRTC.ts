"use client";
import { useState, useRef, useCallback, useEffect } from "react";
import { useCareSessionSignaling } from "./signaling/useCareSessionSignaling";
import { IceCandidateQueue } from "./ice-candidate-queue";
import {
  isMediaStatePayload,
  isPresencePayload,
  type CareSessionParticipantRole,
  type CareSessionSignal,
  type MediaStatePayload,
  type SignalingStatus,
  type SignalingTransport,
} from "./signaling/types";

export type RTCState = "idle" | "connecting" | "waiting" | "connected" | "disconnected" | "error";

interface UseNativeWebRTCOptions {
  careSessionId: string;
  tenantSlug: string;
  role: CareSessionParticipantRole;
  patientJoinToken?: string | null;
  localStream: MediaStream | null;
  transport?: SignalingTransport;
  onRemoteStream?: (stream: MediaStream | null) => void;
  onRemoteConnected?: () => void;
  onRemoteDisconnected?: () => void;
  onRemotePresence?: (status: "joined" | "left" | "reconnecting") => void;
}

const HEARTBEAT_INTERVAL_MS = 15_000;

/**
 * ICE server list. STUN is always present; TURN is added when configured via
 * env vars.
 *
 * PRODUCTION NOTE: STUN alone is NOT sufficient — TURN is mandatory for
 * restricted networks (symmetric NAT, corporate firewalls). TURN credentials
 * should be short-lived and generated by the backend in production
 * (see docs/NATIVE_WEBRTC_CARE_SESSION.md).
 */
function buildIceServers(): RTCIceServer[] {
  const servers: RTCIceServer[] = [
    { urls: process.env.NEXT_PUBLIC_WEBRTC_STUN_URL ?? "stun:stun.l.google.com:19302" },
  ];
  const turnUrl = process.env.NEXT_PUBLIC_WEBRTC_TURN_URL;
  if (turnUrl) {
    servers.push({
      urls: turnUrl,
      username: process.env.NEXT_PUBLIC_WEBRTC_TURN_USERNAME,
      credential: process.env.NEXT_PUBLIC_WEBRTC_TURN_CREDENTIAL,
    });
  }
  return servers;
}

type OfferPayload = { description: RTCSessionDescriptionInit; epoch: number };

/**
 * Native 1:1 WebRTC on top of the transport-agnostic signaling layer
 * (SSE by default — see ./signaling/useCareSessionSignaling).
 *
 * Negotiation design:
 * - Fixed roles avoid offer glare: NUTRITIONIST is the CALLER (creates
 *   offers), PATIENT is the CALLEE (answers).
 * - Every negotiation carries a monotonic `epoch`. The caller re-offers with
 *   a new epoch whenever the remote side (re)joins, and stale offers/answers/
 *   candidates from older epochs are ignored — protecting against races.
 * - ICE candidates arriving before the remote description are QUEUED and
 *   applied right after setRemoteDescription.
 * - Remote camera/mic state comes from explicit `media-state` signals —
 *   never inferred from `track.muted` alone.
 */
export function useNativeWebRTC({
  careSessionId,
  role,
  patientJoinToken,
  localStream,
  transport,
  onRemoteStream,
  onRemoteConnected,
  onRemoteDisconnected,
  onRemotePresence,
}: UseNativeWebRTCOptions) {
  const isCaller = role === "NUTRITIONIST";
  const targetRole: CareSessionParticipantRole = isCaller ? "PATIENT" : "NUTRITIONIST";

  const [rtcState, setRtcState] = useState<RTCState>("idle");
  const [remoteMediaState, setRemoteMediaState] = useState<MediaStatePayload>({
    cameraOn: true,
    micOn: true,
    screenSharing: false,
  });

  const [started, setStarted] = useState(false);

  const pcRef = useRef<RTCPeerConnection | null>(null);
  const localStreamRef = useRef<MediaStream | null>(localStream);
  const remoteStreamRef = useRef<MediaStream | null>(null);
  const remoteConnectedRef = useRef(false);
  // Prevent duplicate disconnect callbacks (connectionstate + hangup signal can both fire)
  const remoteDisconnectedFiredRef = useRef(false);
  const epochRef = useRef(0);
  const remoteDescriptionSetRef = useRef(false);
  const pendingIceCandidatesRef = useRef(new IceCandidateQueue());
  const heartbeatTimerRef = useRef<ReturnType<typeof setInterval> | null>(null);
  const lastMediaStateRef = useRef<MediaStatePayload | null>(null);
  const lastNegotiationAtRef = useRef(0);
  const lastJoinAnnounceAtRef = useRef(0);

  useEffect(() => {
    localStreamRef.current = localStream;
  }, [localStream]);

  // ── send helpers ───────────────────────────────────────────────────────────

  const signalingRef = useRef<ReturnType<typeof useCareSessionSignaling> | null>(null);

  const sendSignalSafe = useCallback(
    async (type: CareSessionSignal["type"], payload: unknown) => {
      try {
        await signalingRef.current?.sendSignal({ type, senderRole: role, targetRole, payload });
      } catch {
        // best-effort: signaling hiccups must never crash the call UI
      }
    },
    [role, targetRole]
  );

  const sendMediaState = useCallback(
    (mediaState: MediaStatePayload) => {
      lastMediaStateRef.current = mediaState;
      void sendSignalSafe("media-state", mediaState);
    },
    [sendSignalSafe]
  );

  // ── disconnect bookkeeping ─────────────────────────────────────────────────

  const fireRemoteDisconnected = useCallback(() => {
    if (remoteDisconnectedFiredRef.current) return;
    remoteDisconnectedFiredRef.current = true;
    remoteConnectedRef.current = false;
    setRtcState("disconnected");
    onRemoteDisconnected?.();
  }, [onRemoteDisconnected]);

  // ── peer lifecycle ─────────────────────────────────────────────────────────

  const closePeer = useCallback(() => {
    const pc = pcRef.current;
    if (pc) {
      pc.onicecandidate = null;
      pc.ontrack = null;
      pc.onconnectionstatechange = null;
      pc.close();
    }
    pcRef.current = null;
    remoteStreamRef.current = null;
    remoteDescriptionSetRef.current = false;
    pendingIceCandidatesRef.current.clear();
  }, []);

  const createPeer = useCallback((epoch: number) => {
    const pc = new RTCPeerConnection({ iceServers: buildIceServers() });

    pc.onicecandidate = (event) => {
      if (event.candidate) {
        void sendSignalSafe("ice-candidate", { candidate: event.candidate.toJSON(), epoch });
      }
    };

    pc.ontrack = (event) => {
      if (!remoteStreamRef.current) {
        remoteStreamRef.current = new MediaStream();
      }
      remoteStreamRef.current.addTrack(event.track);
      onRemoteStream?.(remoteStreamRef.current);
      if (!remoteConnectedRef.current) {
        remoteConnectedRef.current = true;
        remoteDisconnectedFiredRef.current = false;
        onRemoteConnected?.();
        // Make sure the other side knows our current media state.
        if (lastMediaStateRef.current) sendMediaState(lastMediaStateRef.current);
      }
      setRtcState("connected");
    };

    pc.onconnectionstatechange = () => {
      const state = pc.connectionState;
      if (state === "disconnected" || state === "failed" || state === "closed") {
        if (remoteConnectedRef.current) {
          fireRemoteDisconnected();
        } else {
          setRtcState("disconnected");
        }
      } else if (state === "connected") {
        setRtcState("connected");
      }
    };

    const stream = localStreamRef.current;
    if (stream) {
      stream.getTracks().forEach((track) => pc.addTrack(track, stream));
    }

    return pc;
  }, [sendSignalSafe, onRemoteStream, onRemoteConnected, fireRemoteDisconnected, sendMediaState]);

  const drainPendingCandidates = useCallback(async () => {
    const pc = pcRef.current;
    if (!pc || !remoteDescriptionSetRef.current) return;
    // Stale-epoch candidates are dropped by the queue itself.
    for (const candidate of pendingIceCandidatesRef.current.drain(epochRef.current)) {
      try {
        await pc.addIceCandidate(new RTCIceCandidate(candidate));
      } catch {
        // individual bad candidate must not break the rest
      }
    }
  }, []);

  /** Caller side: start a fresh negotiation epoch and send the offer. */
  const negotiateAsCaller = useCallback(async () => {
    if (!localStreamRef.current) return;
    // Debounce: replayed presence signals must not spam fresh peers/offers.
    if (Date.now() - lastNegotiationAtRef.current < 2_000) return;
    lastNegotiationAtRef.current = Date.now();
    epochRef.current = Date.now();
    const epoch = epochRef.current;

    closePeer();
    const pc = createPeer(epoch);
    pcRef.current = pc;

    try {
      const offer = await pc.createOffer();
      await pc.setLocalDescription(offer);
      await sendSignalSafe("offer", { description: offer, epoch } satisfies OfferPayload);
      setRtcState("waiting");
    } catch {
      setRtcState("error");
    }
  }, [closePeer, createPeer, sendSignalSafe]);

  // ── incoming signal handling ───────────────────────────────────────────────

  const handleOffer = useCallback(async (payload: OfferPayload) => {
    if (isCaller) return; // caller never applies offers
    if (!payload?.description || typeof payload.epoch !== "number") return;
    // Ignore offers older than what we're already negotiating (race protection).
    if (payload.epoch < epochRef.current) return;

    // New (or first) epoch → fresh peer.
    if (payload.epoch > epochRef.current || !pcRef.current) {
      epochRef.current = payload.epoch;
      closePeer();
      pcRef.current = createPeer(payload.epoch);
    }

    const pc = pcRef.current;
    if (!pc || pc.signalingState === "closed") return;

    try {
      await pc.setRemoteDescription(new RTCSessionDescription(payload.description));
      remoteDescriptionSetRef.current = true;
      await drainPendingCandidates();
      const answer = await pc.createAnswer();
      await pc.setLocalDescription(answer);
      await sendSignalSafe("answer", { description: answer, epoch: payload.epoch });
      setRtcState("connecting");
    } catch {
      setRtcState("error");
    }
  }, [isCaller, closePeer, createPeer, drainPendingCandidates, sendSignalSafe]);

  const handleAnswer = useCallback(async (payload: OfferPayload) => {
    if (!isCaller) return;
    if (!payload?.description || payload.epoch !== epochRef.current) return; // stale answer
    const pc = pcRef.current;
    if (!pc || pc.signalingState === "closed") return;
    if (pc.signalingState !== "have-local-offer") return; // race protection
    try {
      await pc.setRemoteDescription(new RTCSessionDescription(payload.description));
      remoteDescriptionSetRef.current = true;
      await drainPendingCandidates();
      setRtcState("connecting");
    } catch {
      setRtcState("error");
    }
  }, [isCaller, drainPendingCandidates]);

  const handleIceCandidate = useCallback(async (payload: { candidate?: RTCIceCandidateInit; epoch?: number }) => {
    if (!payload?.candidate) return;
    const epoch = typeof payload.epoch === "number" ? payload.epoch : epochRef.current;
    if (epoch < epochRef.current) return; // stale epoch — drop
    const pc = pcRef.current;
    // Queue when the peer or its remote description isn't ready yet.
    if (!pc || pc.signalingState === "closed" || !remoteDescriptionSetRef.current) {
      pendingIceCandidatesRef.current.enqueue(payload.candidate, epoch);
      return;
    }
    try {
      await pc.addIceCandidate(new RTCIceCandidate(payload.candidate));
    } catch {
      // ignore individual bad candidates
    }
  }, []);

  const handlePresence = useCallback((payload: unknown) => {
    if (!isPresencePayload(payload)) return;
    if (payload.status === "joined") {
      onRemotePresence?.("joined");
      // Caller re-offers whenever the remote side (re)joins — this is what
      // makes reconnection deterministic and lets the SSE stream start "now"
      // without replaying history.
      if (isCaller) void negotiateAsCaller();
      // Re-announce our media state for the newly joined participant.
      if (lastMediaStateRef.current) sendMediaState(lastMediaStateRef.current);
    } else if (payload.status === "left") {
      onRemotePresence?.("left");
      fireRemoteDisconnected();
    } else if (payload.status === "reconnecting") {
      onRemotePresence?.("reconnecting");
    } else if (payload.status === "heartbeat" && !remoteConnectedRef.current) {
      // Self-heal: both sides are alive but not connected (e.g. a lost offer).
      if (isCaller) {
        // Re-offer at most every 10s while unconnected.
        if (Date.now() - lastNegotiationAtRef.current > 10_000) {
          void negotiateAsCaller();
        }
      } else if (Date.now() - lastJoinAnnounceAtRef.current > 10_000) {
        // Callee re-announces itself, prompting the caller to re-offer.
        lastJoinAnnounceAtRef.current = Date.now();
        void sendSignalSafe("presence", { status: "joined" });
      }
    }
  }, [isCaller, negotiateAsCaller, onRemotePresence, fireRemoteDisconnected, sendMediaState, sendSignalSafe]);

  const handleSignal = useCallback((signal: CareSessionSignal) => {
    // Each handler has its own try/catch so one bad signal never stalls the stream.
    switch (signal.type) {
      case "offer":
        void handleOffer(signal.payload as OfferPayload);
        break;
      case "answer":
        void handleAnswer(signal.payload as OfferPayload);
        break;
      case "ice-candidate":
        void handleIceCandidate(signal.payload as { candidate?: RTCIceCandidateInit; epoch?: number });
        break;
      case "media-state":
        if (isMediaStatePayload(signal.payload)) {
          setRemoteMediaState(signal.payload);
        }
        break;
      case "screen-share-started":
        setRemoteMediaState((s) => ({ ...s, screenSharing: true }));
        break;
      case "screen-share-stopped":
        setRemoteMediaState((s) => ({ ...s, screenSharing: false }));
        break;
      case "presence":
        handlePresence(signal.payload);
        break;
      case "hangup":
        fireRemoteDisconnected();
        break;
      case "heartbeat":
        // liveness only — nothing to do
        break;
    }
  }, [handleOffer, handleAnswer, handleIceCandidate, handlePresence, fireRemoteDisconnected]);

  // ── signaling client (SSE default / WebSocket optional / polling fallback) ─

  const signaling = useCareSessionSignaling({
    sessionId: careSessionId,
    role,
    patientJoinToken,
    transport,
    enabled: started,
    onSignal: handleSignal,
  });

  useEffect(() => {
    signalingRef.current = signaling;
  }, [signaling]);

  // ── public API ─────────────────────────────────────────────────────────────

  // stream param allows passing the freshly-acquired stream directly to
  // avoid the React setState async lag when called from handleStart.
  const startCall = useCallback(async (stream?: MediaStream) => {
    const activeStream = stream ?? localStreamRef.current;
    if (!activeStream) return;
    localStreamRef.current = activeStream;

    setRtcState("connecting");
    remoteConnectedRef.current = false;
    remoteDisconnectedFiredRef.current = false;
    setStarted(true); // opens the signaling channel (SSE connects)

    // Announce ourselves. The callee waits for an offer; the caller offers
    // immediately (covers "remote already in the room") AND re-offers when
    // the remote `presence joined` arrives (covers "remote joins later").
    lastJoinAnnounceAtRef.current = Date.now();
    await sendSignalSafe("presence", { status: "joined" });

    if (isCaller) {
      await negotiateAsCaller();
    } else {
      setRtcState("waiting");
    }

    // Presence heartbeat every 15s while in the call.
    if (heartbeatTimerRef.current) clearInterval(heartbeatTimerRef.current);
    heartbeatTimerRef.current = setInterval(() => {
      void sendSignalSafe("presence", { status: "heartbeat" });
    }, HEARTBEAT_INTERVAL_MS);
  }, [isCaller, negotiateAsCaller, sendSignalSafe]);

  const endCall = useCallback(async () => {
    // Reset the UI + tear down media/peer IMMEDIATELY so the user gets instant
    // feedback. The "goodbye" signals are best-effort and must not block the UI
    // (a slow POST used to freeze the leave button).
    if (heartbeatTimerRef.current) {
      clearInterval(heartbeatTimerRef.current);
      heartbeatTimerRef.current = null;
    }
    closePeer();
    onRemoteStream?.(null);
    remoteConnectedRef.current = false;
    remoteDisconnectedFiredRef.current = false;
    epochRef.current = 0;
    setRtcState("idle");

    // Fire-and-forget: notify the other side, then close the channel.
    void (async () => {
      try {
        await sendSignalSafe("hangup", { reason: "user_ended" });
        await sendSignalSafe("presence", { status: "left" });
      } catch {
        // connection may already be gone
      } finally {
        signaling.close();
        setStarted(false);
      }
    })();
  }, [sendSignalSafe, closePeer, onRemoteStream, signaling]);

  /** Replaces the outgoing track of the given kind. Never stops the old track itself. */
  const replaceTrackOfKind = useCallback(async (kind: "video" | "audio", newTrack: MediaStreamTrack | null) => {
    const pc = pcRef.current;
    if (!pc || pc.signalingState === "closed") return;
    const sender = pc.getSenders().find((s) => s.track?.kind === kind);
    if (sender) {
      await sender.replaceTrack(newTrack);
      return;
    }
    // No sender for this kind yet — add the track if we can.
    if (newTrack && localStreamRef.current) {
      try {
        pc.addTrack(newTrack, localStreamRef.current);
      } catch {
        console.warn(`[native-call] could not add ${kind} track: no sender and addTrack failed`);
      }
    } else {
      console.warn(`[native-call] no ${kind} sender available for replaceTrack`);
    }
  }, []);

  const replaceVideoTrack = useCallback(
    (track: MediaStreamTrack | null) => replaceTrackOfKind("video", track),
    [replaceTrackOfKind]
  );
  const replaceAudioTrack = useCallback(
    (track: MediaStreamTrack | null) => replaceTrackOfKind("audio", track),
    [replaceTrackOfKind]
  );

  const notifyScreenShare = useCallback((sharing: boolean) => {
    void sendSignalSafe(sharing ? "screen-share-started" : "screen-share-stopped", {});
  }, [sendSignalSafe]);

  // Cleanup on unmount — peer, timers and signaling channel.
  useEffect(() => () => {
    if (heartbeatTimerRef.current) clearInterval(heartbeatTimerRef.current);
    closePeer();
  }, [closePeer]);

  return {
    rtcState,
    signalingStatus: signaling.status as SignalingStatus,
    signalingTransport: signaling.activeTransport,
    remoteMediaState,
    startCall,
    endCall,
    replaceVideoTrack,
    replaceAudioTrack,
    sendMediaState,
    notifyScreenShare,
  };
}
