import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

// prisma/schema.prisma is generated from the reviewed domain fragments. Edit the fragments, then run
// `npm run prisma:assemble`; `npm run prisma:check` (and the schema-fragments test) fails on drift.
export const fragmentNames = ['core', 'habits-life', 'finance', 'career'];
// Relation fields injected into `model Workspace`. A trailing "?" makes it a one-to-one (`name Type?`).
export const workspaceRelations = {
  Habit: 'habits', HabitSchedule: 'habitSchedules', HabitEntry: 'habitEntries', Task: 'tasks', Project: 'projects', Goal: 'goals',
  Account: 'accounts', FinanceCategory: 'financeCategories', FinanceTransaction: 'financeTransactions', Budget: 'budgets', Subscription: 'subscriptions',
  Debt: 'debts', SavingsGoal: 'savingsGoals', ImportBatch: 'importBatches', ImportMapping: 'importMappings', TransactionRule: 'transactionRules',
  CardStatement: 'cardStatements', CardStatementPayment: 'statementPayments', FinancePlan: 'financePlan?', FixedExpense: 'fixedExpenses',
  FinancialSource: 'financialSources', FinancialSnapshot: 'financialSnapshots', LoanComparison: 'loanComparisons', PersonalAsset: 'personalAssets',
  InvestmentAccount: 'investmentAccounts', InvestmentAsset: 'investmentAssets', InvestmentPosition: 'investmentPositions',
  InvestmentTransaction: 'investmentTransactions', InvestmentIncome: 'investmentIncome', InvestmentBudget: 'investmentBudgets',
  InvestmentAllocationTarget: 'investmentAllocationTargets', InvestmentPortfolioSnapshot: 'investmentPortfolioSnapshots', InvestmentBenchmark: 'investmentBenchmarks',
  InvestmentWatchlist: 'investmentWatchlists', InvestmentResearchNote: 'investmentResearchNotes', InvestmentGoalLink: 'investmentGoalLinks',
  InvestmentTrade: 'investmentTrades', InvestmentPriceAlert: 'investmentPriceAlerts', InvestmentMonthlyReview: 'investmentMonthlyReviews',
  Company: 'companies', Application: 'applications', Contact: 'contacts', Interview: 'interviews', Offer: 'offers', CareerDocument: 'careerDocuments',
};

const header = '// Generated by npm run prisma:assemble from the reviewed domain fragments.\ngenerator client {\n provider = "prisma-client-js"\n}\ndatasource db {\n provider = "postgresql"\n url = env("DATABASE_URL")\n directUrl = env("DIRECT_URL")\n}\n\n';

export function assembleSchema(read = (name) => readFileSync(`prisma/${name}.prisma`, 'utf8')) {
  const fragments = fragmentNames.map(read);
  const lines = Object.entries(workspaceRelations).map(([type, name]) => name.endsWith('?') ? `  ${name.slice(0, -1)} ${type}?` : `  ${name} ${type}[]`);
  fragments[0] = fragments[0].replace('model Workspace {', 'model Workspace {\n' + lines.join('\n'));
  return header + fragments.join('\n\n');
}

const squash = (line) => line.replace(/\s+/g, '');
function blocks(text) {
  const out = new Map();
  for (const match of text.replace(/\r/g, '').matchAll(/^(model|enum) (\w+) \{\n([\s\S]*?)\n\}/gm)) {
    out.set(match[2], new Set(match[3].split('\n').map((line) => squash(line)).filter((line) => line && !line.startsWith('//'))));
  }
  return out;
}
/** Lines that differ between the assembled schema and the committed one, ignoring formatting and order. */
export function schemaDrift(assembled, committed) {
  const a = blocks(assembled), b = blocks(committed), problems = [];
  for (const name of new Set([...a.keys(), ...b.keys()])) {
    if (!a.has(name)) { problems.push(`${name}: only in prisma/schema.prisma (missing from the fragments)`); continue; }
    if (!b.has(name)) { problems.push(`${name}: only in the fragments (not in prisma/schema.prisma)`); continue; }
    for (const line of b.get(name)) if (!a.get(name).has(line)) problems.push(`${name}: schema.prisma has "${line}" but the fragments do not`);
    for (const line of a.get(name)) if (!b.get(name).has(line)) problems.push(`${name}: the fragments have "${line}" but schema.prisma does not`);
  }
  return problems;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const assembled = assembleSchema();
  if (process.argv.includes('--check')) {
    const problems = schemaDrift(assembled, readFileSync('prisma/schema.prisma', 'utf8'));
    if (problems.length) { console.error(`prisma/schema.prisma drifted from the fragments:\n- ${problems.join('\n- ')}`); process.exit(1); }
    console.log('prisma/schema.prisma matches the fragments.');
  } else writeFileSync('prisma/schema.prisma', assembled);
}
