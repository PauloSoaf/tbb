["pt", "en", "es"].forEach((l) => {
  const p = "src/lib/i18n/" + l + ".json";
  const d = JSON.parse(fs.readFileSync(p, "utf8"));
  // Deep merge top-level keys
  Object.entries(keys[l]).forEach(([k, v]) => {
    if (d[k] && typeof d[k] === "object" && typeof v === "object") {
      d[k] = Object.assign({}, d[k], v);
    } else {
      d[k] = v;
    }
  });
  fs.writeFileSync(p, JSON.stringify(d, null, 2), "utf8");
  console.log(l + " ok");
});
